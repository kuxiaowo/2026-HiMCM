    tex = tex.replace(intro, intro + '\n' + GUIDE.strip() + '\n')
    for title, notes in STAGES.items():
        anchor = r'\section{' + title + '}'
        assert tex.count(anchor) == 1, title
        tex = tex.replace(anchor, anchor + '\n' + notes.strip() + '\n')
    pattern = r'\\begin\{equation\}.*?\\label\{eq:([^}]+)\}.*?\\end\{equation\}'
    found = re.findall(pattern, tex, re.S)
    assert len(found) == 19 and set(found) == set(NOTES), found
    tex = re.sub(pattern, lambda m: m.group(0) + '\n' + NOTES[m.group(1)].strip() + '\n', tex, flags=re.S)
    for prefix, notes in INLINE.items():
        lines = tex.splitlines()
        indices = [i for i, line in enumerate(lines) if line.startswith(prefix)]
        assert len(indices) == 1, prefix
        index = indices[0]
        lines.insert(index + 1, '\n' + notes.strip() + '\n')
        tex = '\n'.join(lines) + '\n'
    # Old page comments are original section boundaries, not new verified page numbers.
    tex = re.sub(r'% PAGE (\d+)', r'% ORIGINAL_TRANSLATION_PAGE \1 (not current pagination)', tex)
    old = '脚本检查单位、容量、预算、禁止配置、下限、汇总、引用、图表标签和最终页数。渲染页面已经目视审阅。'
    new = ('英文参赛稿及先前24页中文译文已完成单位、容量、预算、禁止配置、下限、汇总、引用、标签及页数核验，'
           '并已目视审阅。当前中文源在其基础上增加详细讲解，原公式、表内数值与图形保持一致；'
           '新增讲解的分页和预览编译需要单独确认，旧PDF核验不适用于当前新增内容。')
    assert old in tex
    tex = tex.replace(old, new)
    # Verify unchanged mathematical results before saving the watched source.
    equations = lambda value: re.findall(r'\\begin\{equation\}.*?\\end\{equation\}', value, re.S)
    tables = lambda value: re.findall(r'\\begin\{table\}.*?\\end\{table\}', value, re.S)
    figures = lambda value: re.findall(r'\\begin\{figure\}.*?\\end\{figure\}', value, re.S)
    assert equations(tex) == equations(original)
    assert tables(tex) == tables(original)
    assert figures(tex) == figures(original)
    for pattern in [r'\\label\{([^}]+)\}', r'\\cite\{([^}]+)\}', r'\\bibitem\{([^}]+)\}']:
        assert re.findall(pattern, tex) == re.findall(pattern, original)
    # Basic source structure check; this does not stand in for compilation/layout QA.
    stack = []
    for kind, env in re.findall(r'\\(begin|end)\{([^}]+)\}', tex):
        if kind == 'begin':
            stack.append(env)
        else:
            assert stack and stack.pop() == env, env
    assert not stack
    path.write_text(tex, encoding='utf-8')
